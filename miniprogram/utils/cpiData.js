// 已排序的月份键（升序）。
const YMS = Object.keys(LEVELS).sort()

// 时间戳 → 'YYYY-MM'（按本地月份归桶；月边界的时区误差对通胀换算可忽略）。
function ymOf(ms) {
  const d = new Date(ms)
  const m = d.getMonth() + 1
  return d.getFullYear() + '-' + (m < 10 ? '0' + m : '' + m)
}

// 取某时点所在月的价格水平指数。
//   · 早于序列起点 → null（无法向更早换算）
//   · 晚于最新有值月 → 取最新月（clamp forward：当月 CPI 常未发布，用最近可得月，属诚实的“最佳可得”）
//   · 区间内缺月 → 取其前最近的有值月
function levelAt(ms) {
  if (!YMS.length) return null
  const ym = ymOf(ms)
  if (ym < YMS[0]) return null
  let hit = null
  for (let i = 0; i < YMS.length; i++) {
    if (YMS[i] <= ym) hit = LEVELS[YMS[i]]
    else break
  }
  return hit
}

// 从 fromMs 到 toMs 的累计通胀倍数；任一端缺数据 → null（调用方降级）。
function factorBetween(fromMs, toMs) {
  const l0 = levelAt(fromMs)
  const l1 = levelAt(toMs)
  if (l0 == null || l1 == null || l0 === 0) return null
  return l1 / l0
}

// 序列是否覆盖到该时点（用于判断能否换算到那么早）。
function covers(ms) {
  return YMS.length > 0 && ymOf(ms) >= YMS[0]
}

module.exports = { LEVELS, META, BASE_YM, ymOf, levelAt, factorBetween, covers }
