// CPI 月度价格水平指数（内置·真实数据）。
//
// 用途：把过去某时点的名义净值换算成「今天的钱」（购买力），见 services/realworth.js。
// 口径：LEVELS 是一条「定基价格水平指数」（BASE_YM = 100），两点间累计通胀倍数
//   factor(a→b) = level(b月) / level(a月)。构建用「混合锚定法」：
//     · 2022 年内：用官方环比（上月=100）逐月链接打底 level(m)=level(m-1)×环比/100；
//     · 2023 年起：用官方同比锚定 level(m)=level(去年同月)×同比/100。
//   这样任意「满 12 个月」窗口的通胀因子与国家统计局公布的同比 **完全一致**
//   （不能直接连乘同比、基期会重叠，故用此法）。
// 数据诚实（CLAUDE.md 不变量 10）：全部为真实统计局数据（已与逐月新闻稿交叉核对），缺月不臆造；
//   序列没覆盖到的区间，factorBetween 返回 null，调用方降级为只显示名义值。
//
// 更新方式：CPI 每月中旬发布上月数据。发布后按同比追加一行 level(去年同月)×同比/100，并更新 META.latestYm。
//   （三期会加 cpiSync 云函数自动抓取写入 cpiSeries 集合，届时优先读云端、回退本表。）

